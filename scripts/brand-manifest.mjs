// Regenerates apps/web/src/lib/brand.ts from the vendored SVG filenames.
//
// The brand repo ships 79 variants under a strict naming grammar. Turning the
// filenames into a union type means picking the wrong one is a type error rather
// than a 404 nobody notices until it is on a projector.
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const svgDir = join(root, 'apps/web/public/brand')
const out = join(root, 'apps/web/src/lib/brand.ts')

const names = readdirSync(svgDir)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.replace(/\.svg$/, ''))
  .sort()

const file = `// Generated by scripts/brand-manifest.mjs. Do not edit.
// Run \`pnpm brand:manifest\` after \`pnpm brand:sync\`.

/** Every logo variant in the brand guidelines, by filename. */
export const BRAND_LOGOS = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const

export type BrandLogo = (typeof BRAND_LOGOS)[number]

/** Public URL for a logo variant. */
export function brandLogo(name: BrandLogo): string {
  return \`/brand/\${name}.svg\`
}
`

writeFileSync(out, file)
console.log(`Wrote ${names.length} variants to ${out}`)
